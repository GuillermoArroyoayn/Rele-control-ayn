const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const source=fs.readFileSync('relay-installer.js','utf8');
const start=source.indexOf('function technicianWhatsappPhone(');
const end=source.indexOf('function technicianHandoffForm(',start);
assert(start!==-1&&end>start,'Las funciones de invitación deben estar presentes');
const context={};
vm.runInNewContext(source.slice(start,end),context);
const phone=context.technicianWhatsappPhone,message=context.technicianWhatsappMessage;
assert.equal(phone('9 8765 4321'),'56987654321');
assert.equal(phone('+56 9 8765 4321'),'56987654321');
assert.equal(phone('56987654321'),'56987654321');
assert.equal(phone('+54 9 11 5566 7788'),'5491155667788');
for(const bad of ['','123','98765432','hola', '5555555'])assert.throws(()=>phone(bad));
const link='https://rele-control-ayn.vercel.app/instalador.html#token=abc.test';
const text=message({name:'AYN-1'},link);
assert(text.includes('AYN-1')&&text.includes(link),'Texto incluye relé y enlace con código');
assert(text.includes('24 horas'),'Vigencia visible');
assert(source.includes('share.href='+"'https://wa.me/'"),'Abrir WhatsApp al número correcto');
assert(source.includes('share.hidden=false'),'No mostrar enlace antes de generar código');
assert(source.includes("phone.addEventListener('input'"),'Anular propuesta al cambiar destinatario');
assert(source.includes("panel.onsubmit=async event=>"),'Solicitar teléfono antes del token');
assert(source.includes("share.rel='noopener noreferrer'"),'Aislar apertura de WhatsApp');
console.log('WhatsApp de instalador OK: números Chile/internacionales, validación, código preincluido y envío manual.');
